// Helper function to get destination by ID
export const getDestinationById = (destinationId) => {
  return destinationsWithPlaces[destinationId] || null
}

// Helper function to get all destinations as array
export const getAllDestinations = () => {
  return Object.values(destinationsWithPlaces)
}

// Helper function to calculate total distance for selected places
export const calculateTotalDistance = (destinationId, selectedPlaceIds) => {
  const destination = destinationsWithPlaces[destinationId]
  if (!destination) return 0
  
  const selectedPlaces = destination.places.filter(place => 
    selectedPlaceIds.includes(place.id)
  )
  
  // Calculate round trip distance (sum of all distances × 2 for return journey)
  const oneWayDistance = selectedPlaces.reduce((sum, place) => sum + place.distance, 0)
  return oneWayDistance * 2 // Round trip
}

// Helper function to get place names
export const getPlaceNames = (destinationId, placeIds) => {
  const destination = destinationsWithPlaces[destinationId]
  if (!destination) return []
  
  return destination.places
    .filter(place => placeIds.includes(place.id))
    .map(place => place.name)
}
